/* ---------- low-level SSD1306 ---------- */

static esp_err_t oled_send_cmds(const uint8_t *cmds, size_t len)
{
    uint8_t buf[32];
    buf[0] = 0x00;                       // control byte: command stream
    memcpy(&buf[1], cmds, len);
    return i2c_master_transmit(oled_dev, buf, len + 1, 100);
}

static esp_err_t oled_flush(void)
{
    const uint8_t addr[] = {0x21, 0, OLED_W - 1, 0x22, 0, OLED_PAGES - 1};
    esp_err_t err = oled_send_cmds(addr, sizeof(addr));
    if (err != ESP_OK) return err;

    uint8_t buf[OLED_W + 1];
    buf[0] = 0x40;                       // control byte: data stream
    for (int page = 0; page < OLED_PAGES; page++) {
        memcpy(&buf[1], &fb[page * OLED_W], OLED_W);
        err = i2c_master_transmit(oled_dev, buf, sizeof(buf), 100);
        if (err != ESP_OK) return err;
    }
    return ESP_OK;
}

/* ---------- drawing helpers ---------- */

static void fb_clear(void) { memset(fb, 0, sizeof(fb)); }

static void fb_pixel(int x, int y)
{
    if (x < 0 || x >= OLED_W || y < 0 || y >= OLED_H) return;
    fb[(y / 8) * OLED_W + x] |= (1 << (y % 8));
}

static void draw_char(int x, int y, char c, int scale)
{
    if (c < 32 || c > 126) c = '?';
    for (int col = 0; col < 5; col++) {
        uint8_t bits = font5x7[c - 32][col];
        for (int row = 0; row < 7; row++) {
            if (bits & (1 << row)) {
                for (int dx = 0; dx < scale; dx++)
                    for (int dy = 0; dy < scale; dy++)
                        fb_pixel(x + col * scale + dx, y + row * scale + dy);
            }
        }
    }
}

static void draw_text(int x, int y, const char *s, int scale)
{
    for (; *s; s++) {
        draw_char(x, y, *s, scale);
        x += 6 * scale;                  // 5 px glyph + 1 px spacing
    }
}

/* ---------- public API ---------- */

void display_init(void)
{
    i2c_master_bus_config_t bus_cfg = {
        .i2c_port          = I2C_NUM_0,
        .sda_io_num        = OLED_SDA_GPIO,
        .scl_io_num        = OLED_SCL_GPIO,
        .clk_source        = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    i2c_master_bus_handle_t bus;
    ESP_ERROR_CHECK(i2c_new_master_bus(&bus_cfg, &bus));

    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address  = OLED_ADDR,
        .scl_speed_hz    = 400000,
    };
    ESP_ERROR_CHECK(i2c_master_bus_add_device(bus, &dev_cfg, &oled_dev));

    const uint8_t init[] = {
        0xAE,             // display off
        0xD5, 0x80,       // clock divide
        0xA8, 0x3F,       // multiplex 1/64
        0xD3, 0x00,       // display offset
        0x40,             // start line
        0x8D, 0x14,       // charge pump on
        0x20, 0x00,       // horizontal addressing mode
        0xA1, 0xC8,       // segment remap + COM scan direction
        0xDA, 0x12,       // COM pins
        0x81, 0xCF,       // contrast
        0xD9, 0xF1,       // pre-charge
        0xDB, 0x40,       // VCOMH
        0xA4, 0xA6,       // resume RAM, normal (not inverted)
        0xAF              // display on
    };
    ESP_ERROR_CHECK(oled_send_cmds(init, sizeof(init)));

    fb_clear();
    ESP_ERROR_CHECK(oled_flush());
}

static void render_temperature(float temperature)
{
    char line[16];
    fb_clear();
    draw_text(0, 0, "ROOM MONITOR", 1);
    draw_text(0, 18, "Temperature", 1);
    snprintf(line, sizeof(line), "%.1f C", temperature);
    draw_text(0, 36, line, 3);
    if (oled_flush() != ESP_OK) {
        ESP_LOGE(TAG, "OLED flush failed");
    }
}

void DisplayTask(void *pvParameters)
{
    SensorData data;
    for (;;)
    {
        // Blocks (Blocked state) until SensorTask publishes new data
        if (xQueueReceive(displayQueue, &data, portMAX_DELAY) == pdTRUE) {
            render_temperature(data.temperature);
        }
    }
}